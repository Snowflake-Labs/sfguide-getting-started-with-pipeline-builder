-- Cleanup for Getting Started with Pipeline Builder
--
-- Purge each DCM project before you drop it. Dropping a DCM project without
-- purging it first leaves its tasks and task graphs in your account as
-- unmanaged objects. If your project names differ, check them with:
-- SHOW DCM PROJECTS IN SCHEMA TASTY_PIPELINE_QS_DB.PIPELINE;

-- 1. As the guide role, purge and drop the DCM projects
USE ROLE TASTY_PIPELINE_QS_ROLE;

EXECUTE DCM PROJECT TASTY_PIPELINE_QS_DB.PIPELINE.PIPELINE_BUILDER_QUICKSTART PURGE AS "quickstart cleanup";
DROP DCM PROJECT IF EXISTS TASTY_PIPELINE_QS_DB.PIPELINE.PIPELINE_BUILDER_QUICKSTART;

-- Only if you deployed the CoCo pipeline
-- EXECUTE DCM PROJECT TASTY_PIPELINE_QS_DB.PIPELINE.TASTY_MENU_POPULARITY PURGE AS "quickstart cleanup";
-- DROP DCM PROJECT IF EXISTS TASTY_PIPELINE_QS_DB.PIPELINE.TASTY_MENU_POPULARITY;

-- 2. As ACCOUNTADMIN, drop the account-level objects
USE ROLE ACCOUNTADMIN;

DROP DATABASE IF EXISTS TASTY_PIPELINE_QS_DB;
ALTER COMPUTE POOL IF EXISTS TASTY_PIPELINE_QS_POOL STOP ALL;
DROP COMPUTE POOL IF EXISTS TASTY_PIPELINE_QS_POOL;
DROP WAREHOUSE IF EXISTS TASTY_PIPELINE_QS_WH;
DROP INTEGRATION IF EXISTS TASTY_PIPELINE_QS_GIT_INT;
DROP ROLE IF EXISTS TASTY_PIPELINE_QS_ROLE;
